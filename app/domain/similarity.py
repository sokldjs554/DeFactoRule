"""요청문 유사도의 문턱 — **한 곳에서만 정한다.**

## 왜 이 파일이 있는가

같은 것을 재는 문턱이 세 파일에 흩어져 있었고, 값이 서로 달랐다.

    confusable.SIMILARITY_FLOOR = 0.25   TRAP 파티션의 CLI 기본값
    neighbor.MEDIUM             = 0.15   검색 기준선의 신뢰도 구간
    trap.json  similarity_floor = 0.15   **발표된 표를 만든 값**

그래서 `python3 scripts/confusable.py` 를 인자 없이 돌리면 문서에 실린 표가
나오지 않았다. 실측으로 확인한 차이는 이만큼이다.

    floor 0.15   순응 72 · 함정 15 · 선례 없음  83   <- 문서에 실린 값
    floor 0.25   순응 57 · 함정 10 · 선례 없음 103

**함정 구간이 15건에서 10건으로 바뀐다.** Phase 3 의 주 종점이 그 구간 위에
있으므로, Router 를 얹기 전에 이것부터 하나로 모은다.

## 값의 근거

`DOUBT` 0.15 와 `TRUST` 0.60 은 임의로 고른 값이 아니다. dev 85건을
leave-one-out 으로 재보면 선례를 그대로 따랐을 때의 오류율이 이렇게 갈린다.

    유사도 >= 0.60   32건   오류율 0.062   95% CI [0.017, 0.201]
    0.15 ~ 0.60       5건   오류율 0.400
    유사도 <  0.15   48건   오류율 0.500   95% CI [0.364, 0.636]

두 끝 구간의 신뢰구간이 겹치지 않는다. 그리고 85건 중 80건이 두 끝에 몰려
있어 가운데는 5건뿐이다 — 그래서 구간을 잘게 자르지 않는다.

재현: `python3 scripts/calibrate.py`
"""

from __future__ import annotations

# 이 아래면 "닮았다" 고 부르지 않는다. 선례를 따르면 절반이 틀린다.
DOUBT = 0.15

# 이 위면 선례를 따를 만하다. dev 에서 오류율 0.062.
TRUST = 0.60

# TRAP 파티션(순응/함정/선례없음)을 가르는 문턱. 발표된 수치와 같아야 한다.
SIMILARITY_FLOOR = DOUBT
