"""회답 결론 라벨 정의.

이 프로젝트가 최종적으로 찾으려는 것은 규제당국이 공표한 적 없는 판단 기준이다.
그 첫 단계는 "이 회답이 어떤 결론인가"를 라벨로 만드는 것이다.

비조치의견서는 결론이 체크박스로 문서에 박혀 있어 라벨이 공짜다. 그러나 분포가
184:49:22 로 무너져 있어 단독 학습이 어렵다.

법령해석 회신문은 라벨이 없다. 회답 본문에서 판정해야 하며, **그 판정이 바로 이
프로젝트가 측정하려는 대상**이다. 그래서 파서 단계에서 규칙으로 확정하지 않았다.

라벨 체계에 `판단유보` 를 둔 것은 편의가 아니라 이 도메인의 실체다. 규제당국은
"개별 사실관계에 따라 달라진다" 는 회답을 자주 낸다. 그것을 긍정이나 부정으로
욱여넣으면 데이터가 거짓이 되고, 나중에 Agent 가 "언제 판단하면 안 되는가" 를
배울 근거도 사라진다.
"""

from __future__ import annotations

from enum import StrEnum


class Verdict(StrEnum):
    """법령해석 회답의 결론."""

    AFFIRM = "긍정"  # 질의한 행위·해석이 가능하다 / 해당한다
    DENY = "부정"  # 불가하다 / 해당하지 않는다
    CONDITIONAL = "조건부"  # 조건을 갖추면 가능하다
    ABSTAIN = "판단유보"  # 개별 사실관계에 따라 다르다 / 답할 수 없다


class NonAction(StrEnum):
    """비조치의견서의 결론. 문서의 체크박스에서 그대로 읽는다."""

    NO_ACTION = "비조치"
    ACTION = "조치"
    OTHER = "기타"


VERDICTS = tuple(v.value for v in Verdict)
NON_ACTIONS = tuple(v.value for v in NonAction)

